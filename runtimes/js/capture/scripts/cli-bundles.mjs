// The scripts `glossa capture` embeds (RFC 0004 §3.2), bundled from this
// package's sources into the Go tree. `pnpm build:cli` writes them;
// src/cli-bundles.test.ts fails when a checked-in file differs from a fresh
// build, so the CLI never ships a stale capture script.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cli = join(root, "../../../platform/internal/cli/capture");

const banner = (what) =>
  `// Code generated by \`pnpm --filter @klarlabs-studio/glossa-capture build:cli\` from runtimes/js/capture; DO NOT EDIT.\n// ${what}`;

/** Every generated file: its path and its contents. */
export const bundles = [
  {
    path: join(cli, "agent.js"),
    what: "The capture agent glossa capture injects before a page's scripts (src/agent.ts).",
    contents: `import { install } from "./src/agent.ts";\ninstall();\n`,
  },
  {
    path: join(cli, "testdata/app/app.js"),
    what: "The integration test's fixture app (src/testing/cli-fixture.ts).",
    // An entry point of its own: as an import, "sideEffects": false would drop it.
    entry: join(root, "src/testing/cli-fixture.ts"),
  },
];

/** Bundle one entry: a minified IIFE for current Chromium. */
export async function bundle(b) {
  const out = await build({
    ...(b.entry
      ? { entryPoints: [b.entry] }
      : { stdin: { contents: b.contents, resolveDir: root, loader: "ts", sourcefile: "entry.ts" } }),
    bundle: true,
    minify: true,
    format: "iife",
    target: "chrome120",
    platform: "browser",
    legalComments: "none",
    banner: { js: banner(b.what) },
    write: false,
    logLevel: "silent",
  });
  return out.outputFiles[0].text;
}

/** The checked-in contents of a bundle's file, or "" when it doesn't exist. */
export async function checkedIn(b) {
  try {
    return await readFile(b.path, "utf8");
  } catch {
    return "";
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const b of bundles) {
    await writeFile(b.path, await bundle(b));
    console.log(`wrote ${b.path}`);
  }
}
