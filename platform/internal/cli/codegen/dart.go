// DartType is the Dart type of an argument's value. The Dart runtime's
// formatter takes a DateTime, an ISO-8601 String or epoch milliseconds
// for a date; the generated accessor asks for the unambiguous one.
func DartType(a mf.Argument) string {
	switch a.Type {
	case mf.ArgInteger:
		return "int"
	case mf.ArgNumber, mf.ArgPercent, mf.ArgCurrency, mf.ArgUnit:
		return "num"
	case mf.ArgDate, mf.ArgTime, mf.ArgDatetime:
		return "DateTime"
	}
	return "String"
}

// DartOptions configure Dart.
type DartOptions struct {
	// Runtime is the import URI of the Dart runtime.
	Runtime string
	Source  string
}

// reservedDart are the words a generated member or parameter can't be
// called: Dart's reserved words, the members every Object has, and the
// names the generated classes declare themselves.
var reservedDart = map[string]bool{
	"assert": true, "break": true, "case": true, "catch": true, "class": true,
	"const": true, "continue": true, "default": true, "do": true, "else": true,
	"enum": true, "extends": true, "false": true, "final": true, "finally": true,
	"for": true, "if": true, "in": true, "is": true, "new": true, "null": true,
	"rethrow": true, "return": true, "super": true, "switch": true, "this": true,
	"throw": true, "true": true, "try": true, "var": true, "void": true,
	"while": true, "with": true, "required": true,
	"hashCode": true, "noSuchMethod": true, "runtimeType": true, "toString": true,
	"translate": true, "of": true, "defaultText": true,
}

var dartIdent = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// dartName makes name a usable Dart member or parameter name, unique
// among used. suffix distinguishes a mangled name from the original.
func dartName(name, suffix string, used map[string]bool) string {
	n := camel(name)
	n = strings.TrimPrefix(n, "_")
	if n == "" || !dartIdent.MatchString(n) || reservedDart[n] {
		n += suffix
	}
	for used[n] {
		n += "_"
	}
	used[n] = true
	return n
}

// dartClass is the class name of the accessor group at segs.
func dartClass(segs []string, used map[string]bool) string {
	name := pascal(strings.Join(segs, "_")) + "Messages"
	for used[name] {
		name += "_"
	}
	used[name] = true
	return name
}

// dartDoc is a message's documentation for a `///` comment. It undoes
// comment()'s `*/` escape, which only a C-style comment needs.
func dartDoc(e Entry) string {
	return strings.ReplaceAll(docText(e), `*\/`, "*/")
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

// Dart renders typed accessors for the Dart and Flutter runtime: a
// Messages tree whose leaves take named, typed arguments
// (messages.checkout.pay(amount: …)), plus MessageIds for dynamic use.
//
// The accessors talk to a GlossaTranslate, which GlossaClient.t,
// Localizer.t and package:glossa_flutter's Glossa.t all satisfy, so one
// generated file serves a server, a CLI and a Flutter app.
func Dart(entries []Entry, opts DartOptions) ([]byte, []Warning) {
	entries = sortEntries(entries)
	keys := make([]string, len(entries))
	for i, e := range entries {
		keys[i] = e.Key
	}
	paths, warnings := tsPaths(keys)

	var classes strings.Builder
	classNames := map[string]bool{"Messages": true, "MessageIds": true}
	writeDartClass(&classes, "Messages", nil, buildTree(entries, paths), classNames, true)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by glossa generate from %s. DO NOT EDIT.\n", opts.Source)
	b.WriteString("// ignore_for_file: type=lint\n")
	// The file is laid out here, not by dart_style, which this generator
	// can't run: `dart format` on the project must therefore leave it
	// alone, or every run of it would make `glossa generate --check` fail.
	b.WriteString("// dart format off\n\n")
	fmt.Fprintf(&b, "import %s;\n", dartString(opts.Runtime))
	b.WriteString(dartPrelude)
	b.WriteString(classes.String())
	b.WriteString("\n/// The message ids, for the calls that take one:\n" +
		"/// `GlossaText`, `Localizer.t`, `explain()`.\nabstract final class MessageIds {")
	idNames := map[string]bool{}
	for _, e := range entries {
		if _, ok := paths[e.Key]; !ok {
			continue
		}
		name := dartName(lowerFirst(pascal(e.Key)), "Id", idNames)
		fmt.Fprintf(&b, "\n  /// `%s` — %s\n", e.Key, dartDoc(e))
		fmt.Fprintf(&b, "  static const String %s = %s;\n", name, dartString(e.Key))
	}
	b.WriteString("}\n")
	return []byte(b.String()), warnings
}

// writeDartClass writes the class for one node of the accessor tree and,
// after it, the classes of its groups.
func writeDartClass(b *strings.Builder, class string, path []string, node *tree, classNames map[string]bool, root bool) {
	names := make([]string, 0, len(node.children))
	for n := range node.children {
		names = append(names, n)
	}
	sort.Strings(names)

	type group struct {
		class string
		segs  []string
		node  *tree
	}
	var (
		groups  []group
		members strings.Builder
		used    = map[string]bool{}
	)
	for _, n := range names {
		child := node.children[n]
		segs := append(append([]string(nil), path...), n)
		if child.entry == nil {
			g := group{class: dartClass(segs, classNames), segs: segs, node: child}
			groups = append(groups, g)
			name := dartName(n, "Group", used)
			fmt.Fprintf(&members, "\n  /// The `%s` messages.\n", strings.Join(segs, "."))
			fmt.Fprintf(&members, "  %s get %s => %s(translate);\n", g.class, name, g.class)
			continue
		}
		writeDartAccessor(&members, dartName(n, "Message", used), *child.entry)
	}

	if root {
		b.WriteString("\n/// The project's messages, with typed arguments:\n" +
			"///\n" +
			"/// ```dart\n" +
			"/// final messages = Messages.of(glossa);\n" +
			"/// messages.checkout.pay(amount: order.total);\n" +
			"/// ```\n" +
			"class Messages {\n" +
			"  /// Binds the accessors to [translate].\n" +
			"  const Messages(this.translate);\n\n" +
			"  /// Binds the accessors to a runtime.\n" +
			"  Messages.of(GlossaClient client) : translate = client.t;\n\n" +
			"  /// How a message id becomes a string.\n" +
			"  final GlossaTranslate translate;\n")
	} else {
		fmt.Fprintf(b, "\n/// The `%s` messages.\nclass %s {\n", strings.Join(path, "."), class)
		fmt.Fprintf(b, "  /// Binds the group to [translate].\n  const %s(this.translate);\n\n", class)
		b.WriteString("  /// How a message id becomes a string.\n  final GlossaTranslate translate;\n")
	}
	b.WriteString(members.String())
	b.WriteString("}\n")

	for _, g := range groups {
		writeDartClass(b, g.class, g.segs, g.node, classNames, false)
	}
}

// dartWrap is the column a parameter list is split at. The layout is
// this generator's own (the file carries `// dart format off`), so the
// only thing that matters is that it is deterministic.
const dartWrap = 76

// writeDartAccessor writes one message's method.
func writeDartAccessor(b *strings.Builder, name string, e Entry) {
	used := map[string]bool{}
	var params, args []string
	for _, a := range e.Arguments {
		p := dartName(a.Name, "Arg", used)
		params = append(params, fmt.Sprintf("required %s %s", DartType(a), p))
		args = append(args, fmt.Sprintf("%s: %s", dartString(a.Name), p))
	}
	// SPEC §3.5: the inline default belongs at the call site.
	params = append(params, "String? defaultText")

	fmt.Fprintf(b, "\n  /// %s\n", dartDoc(e))
	fmt.Fprintf(b, "  ///\n  /// Renders `%s`.\n", e.Key)
	signature := fmt.Sprintf("  String %s({%s}) => translate(", name, strings.Join(params, ", "))
	if len(signature) > dartWrap {
		fmt.Fprintf(b, "  String %s({\n", name)
		for _, p := range params {
			fmt.Fprintf(b, "    %s,\n", p)
		}
		b.WriteString("  }) => translate(\n")
	} else {
		b.WriteString(signature + "\n")
	}
	fmt.Fprintf(b, "    %s,\n", dartString(e.Key))
	if len(args) > 0 {
		fmt.Fprintf(b, "    values: {%s},\n", strings.Join(args, ", "))
	}
	b.WriteString("    defaultText: defaultText,\n  );\n")
}

// dartString quotes s as a single-quoted Dart string literal, which is
// what `prefer_single_quotes` and `dart format` want.
func dartString(s string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range s {
		switch r {
		case '\'', '\\', '$':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('\'')
	return b.String()
}

const dartPrelude = `
/// Renders a message by id.
///
/// ` + "`GlossaClient.t`" + `, ` + "`Localizer.t`" + ` and ` + "`Glossa.t`" + ` in
/// package:glossa_flutter all match it, so the same accessors serve a
/// server, a CLI and a Flutter app.
typedef GlossaTranslate = String Function(
  String id, {
  Map<String, Object?> values,
  String? defaultText,
});
`
